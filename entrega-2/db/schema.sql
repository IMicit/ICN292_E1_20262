CREATE TABLE informe_visita (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_id       bigint       NOT NULL REFERENCES visita(id)  ON DELETE RESTRICT,
    generado_por_id bigint       NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    version         smallint     NOT NULL CHECK (version > 0),
    archivo         varchar(100) NOT NULL,
    hash_sha256     char(64)     NOT NULL,
    bytes           integer      NOT NULL CHECK (bytes > 0),
    destinatario    varchar(254) NOT NULL DEFAULT '',
    ts              timestamptz  NOT NULL DEFAULT now(),
    ts_despacho     timestamptz,
    CONSTRAINT uq_informe_visita_version UNIQUE (visita_id, version)
);

COMMENT ON TABLE informe_visita IS 'Informe archivado con su propia huella. Regenerarlo crea una versión nueva: las anteriores no se borran, porque el documento que se le envió al cliente tiene que poder recuperarse idéntico meses después.';


CREATE TABLE libro_anual (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio               smallint     NOT NULL UNIQUE CHECK (anio BETWEEN 2000 AND 2100),
    actualizado_por_id bigint       REFERENCES usuario(id) ON DELETE SET NULL,
    archivo            varchar(100) NOT NULL DEFAULT '',
    n_visitas          smallint     NOT NULL DEFAULT 0,
    bytes              integer      NOT NULL DEFAULT 0,
    ts_actualizacion   timestamptz
);

COMMENT ON TABLE libro_anual IS 'Planilla anual de control. Es la única salida que NO es append-only, y la diferencia es deliberada: no es evidencia, es una vista derivada que se regenera entera para que el archivo y el sistema no puedan decir cosas distintas.';


