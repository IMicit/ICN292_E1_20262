DROP TABLE IF EXISTS libro_anual, informe_visita, medicion_electrica, hallazgo,
    observacion, evidencia_item, evidencia, registro_item, registro_tablero,
    pendiente, visita_cuadrilla, visita, ciclo, item_checklist, seccion_checklist,
    tablero, local, cliente, usuario CASCADE;


-- =============================================================================
--  1. PERSONAS Y ACCESO
-- =============================================================================

CREATE TABLE usuario (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    varchar(150) NOT NULL UNIQUE,
    first_name  varchar(150) NOT NULL DEFAULT '',
    last_name   varchar(150) NOT NULL DEFAULT '',
    email       varchar(254) NOT NULL DEFAULT '',
    password    varchar(128) NOT NULL,
    rol         varchar(20)  NOT NULL DEFAULT 'TECNICO',
    is_active   boolean      NOT NULL DEFAULT true,
    date_joined timestamptz  NOT NULL DEFAULT now(),
    -- Infraestructura de autenticación, no parte del modelo de negocio.
    last_login   timestamptz,
    is_superuser boolean     NOT NULL DEFAULT false,
    is_staff     boolean     NOT NULL DEFAULT false,
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('TECNICO', 'ADMINISTRACION', 'GERENCIA'))
);

COMMENT ON TABLE  usuario IS 'Personas que operan el sistema. El perfil decide qué puede hacer cada una (RF-14, RNF-05).';
COMMENT ON COLUMN usuario.rol IS 'TECNICO registra en terreno; ADMINISTRACION revisa y despacha; GERENCIA sólo consulta.';


-- =============================================================================
--  2. CATÁLOGO MAESTRO
-- =============================================================================

CREATE TABLE cliente (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social   varchar(120) NOT NULL,
    unidad_negocio varchar(80)  NOT NULL DEFAULT ''
);

COMMENT ON TABLE cliente IS 'Cliente corporativo que contrata la mantención preventiva.';


CREATE TABLE local (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id bigint       NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    nombre     varchar(120) NOT NULL,
    direccion  varchar(200) NOT NULL,
    comuna     varchar(80)  NOT NULL
);

CREATE INDEX ix_local_cliente ON local(cliente_id);
COMMENT ON TABLE local IS 'Local del cliente donde se ejecuta la visita de mantención.';


CREATE TABLE tablero (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id  bigint       NOT NULL REFERENCES local(id) ON DELETE RESTRICT,
    codigo    varchar(40)  NOT NULL,
    ubicacion varchar(150) NOT NULL,
    tipo      varchar(20)  NOT NULL DEFAULT 'DISTRIBUCION',
    activo    boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_tablero_local_codigo UNIQUE (local_id, codigo),
    CONSTRAINT ck_tablero_tipo CHECK (tipo IN ('FUERZA', 'DISTRIBUCION', 'ALUMBRADO', 'EMERGENCIA'))
);

CREATE INDEX ix_tablero_local ON tablero(local_id);
COMMENT ON TABLE  tablero IS 'Unidad de cobertura del proceso. Sin esta tabla no existe forma de saber qué falta por revisar: es el origen del problema que el sistema resuelve.';
COMMENT ON CONSTRAINT uq_tablero_local_codigo ON tablero IS 'El código identifica al tablero dentro de su local, no globalmente.';


-- =============================================================================
--  3. PAUTA DE MANTENCIÓN
--  Digitalización literal de la ficha «LISTA DE CHEQUEO MANTENIMIENTO
--  PREVENTIVO ELECTRICO N° 002190» de IMELSE.
-- =============================================================================

CREATE TABLE seccion_checklist (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero smallint     NOT NULL UNIQUE CHECK (numero > 0),
    nombre varchar(150) NOT NULL
);


CREATE TABLE item_checklist (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seccion_id  bigint       NOT NULL REFERENCES seccion_checklist(id) ON DELETE RESTRICT,
    orden       smallint     NOT NULL CHECK (orden > 0),
    descripcion varchar(250) NOT NULL,
    ambito      varchar(10)  NOT NULL DEFAULT 'TABLERO',
    obligatorio boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_item_seccion_orden UNIQUE (seccion_id, orden),
    CONSTRAINT ck_item_ambito CHECK (ambito IN ('TABLERO', 'VISITA'))
);

COMMENT ON TABLE  item_checklist IS 'La pauta vive como dato, no escrita dentro del código: si la empresa agrega un punto de control, se agrega una fila.';
COMMENT ON COLUMN item_checklist.ambito IS 'TABLERO se responde una vez por cada tablero; VISITA una sola vez por visita. Esta separación es la única adición del rediseño y es exactamente la trazabilidad que el formato en papel no permitía.';


-- =============================================================================
--  4. PLANIFICACIÓN
-- =============================================================================

CREATE TABLE ciclo (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio         smallint NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    periodo      smallint NOT NULL CHECK (periodo BETWEEN 1 AND 6),
    fecha_inicio date     NOT NULL,
    CONSTRAINT uq_ciclo_anio_periodo UNIQUE (anio, periodo)
);

COMMENT ON TABLE  ciclo IS 'Período de cumplimiento del contrato. Seis ciclos bimensuales al año.';


CREATE TABLE visita (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id       bigint      NOT NULL REFERENCES local(id) ON DELETE RESTRICT,
    ciclo_id       bigint      NOT NULL REFERENCES ciclo(id) ON DELETE RESTRICT,
    fecha          date        NOT NULL,
    estado         varchar(15) NOT NULL DEFAULT 'PLANIFICADA',
    cerrada_por_id bigint      REFERENCES usuario(id) ON DELETE RESTRICT,
    ts_cierre      timestamptz,
    CONSTRAINT uq_visita_local_ciclo UNIQUE (local_id, ciclo_id),
    CONSTRAINT ck_visita_estado CHECK (estado IN ('PLANIFICADA', 'EN_EJECUCION', 'CERRADA')),
    CONSTRAINT ck_visita_cierre CHECK (
        (estado = 'CERRADA' AND ts_cierre IS NOT NULL AND cerrada_por_id IS NOT NULL)
        OR (estado <> 'CERRADA' AND ts_cierre IS NULL)
    )
);

CREATE INDEX ix_visita_ciclo ON visita(ciclo_id);
CREATE INDEX ix_visita_fecha ON visita(fecha);
COMMENT ON CONSTRAINT uq_visita_local_ciclo ON visita IS 'Un local se visita una vez por ciclo: evita el registro duplicado de una misma mantención.';
COMMENT ON CONSTRAINT ck_visita_cierre ON visita IS 'Una visita cerrada siempre sabe quién la cerró y cuándo. La atribución no es opcional.';


CREATE TABLE visita_cuadrilla (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_id  bigint NOT NULL REFERENCES visita(id)  ON DELETE CASCADE,
    usuario_id bigint NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    CONSTRAINT uq_cuadrilla UNIQUE (visita_id, usuario_id)
);

COMMENT ON TABLE visita_cuadrilla IS 'Relación N:M entre visita y los técnicos que la ejecutan.';


-- =============================================================================
--  5. EJECUCIÓN EN TERRENO — tablas append-only
--
--  Ninguna fila de esta sección se actualiza ni se elimina después de cerrada.
--  La aplicación lo impide a nivel de modelo de datos, no de interfaz, para
--  que ningún camino del código pueda saltárselo (RNF-02).
-- =============================================================================

CREATE TABLE registro_tablero (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_id  bigint      NOT NULL REFERENCES visita(id)  ON DELETE RESTRICT,
    tablero_id bigint      NOT NULL REFERENCES tablero(id) ON DELETE RESTRICT,
    usuario_id bigint      NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    ts_inicio  timestamptz NOT NULL DEFAULT now(),
    ts_cierre  timestamptz,
    cerrado    boolean     NOT NULL DEFAULT false,
    CONSTRAINT ck_registro_cerrado CHECK (
        (cerrado AND ts_cierre IS NOT NULL) OR (NOT cerrado AND ts_cierre IS NULL)
    )
);

CREATE INDEX ix_regtab_visita  ON registro_tablero(visita_id);
CREATE INDEX ix_regtab_tablero ON registro_tablero(tablero_id);
COMMENT ON TABLE registro_tablero IS 'Agrupa el trabajo declarado sobre un tablero dentro de una visita. Al sellarlo (cerrado = true) el conjunto queda inmutable.';


CREATE TABLE registro_item (
    id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_id           bigint      NOT NULL REFERENCES visita(id)           ON DELETE RESTRICT,
    registro_tablero_id bigint      REFERENCES registro_tablero(id)          ON DELETE RESTRICT,
    item_id             bigint      NOT NULL REFERENCES item_checklist(id)   ON DELETE RESTRICT,
    usuario_id          bigint      NOT NULL REFERENCES usuario(id)          ON DELETE RESTRICT,
    corrige_a_id        bigint      REFERENCES registro_item(id)             ON DELETE RESTRICT,
    resultado           varchar(2)  NOT NULL,
    justificacion       text        NOT NULL DEFAULT '',
    ts_captura          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_regitem_resultado CHECK (resultado IN ('SI', 'NO', 'NA')),
    CONSTRAINT ck_regitem_justificacion CHECK (
        resultado = 'SI' OR length(trim(justificacion)) > 0
    )
);

CREATE INDEX ix_regitem_visita  ON registro_item(visita_id);
CREATE INDEX ix_regitem_regtab  ON registro_item(registro_tablero_id);
CREATE INDEX ix_regitem_item    ON registro_item(item_id);
COMMENT ON TABLE  registro_item IS 'Respuesta a un punto de la pauta. Es el dato atómico del sistema.';
COMMENT ON COLUMN registro_item.registro_tablero_id IS 'Nulo cuando el ítem es de ámbito visita y no de un tablero concreto.';
COMMENT ON COLUMN registro_item.corrige_a_id IS 'Apunta a la respuesta anterior cuando ésta es una corrección. Las dos filas quedan en la tabla: ninguna se sobrescribe.';
COMMENT ON CONSTRAINT ck_regitem_justificacion ON registro_item IS 'Simetría de la regla: no se declara hecho sin prueba (evidencia), y no se declara no hecho sin decir por qué. El casillero mudo del papel no tiene equivalente aquí.';


CREATE TABLE evidencia (
    id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_tablero_id bigint      NOT NULL REFERENCES registro_tablero(id) ON DELETE RESTRICT,
    usuario_id          bigint      NOT NULL REFERENCES usuario(id)          ON DELETE RESTRICT,
    archivo             varchar(100) NOT NULL,
    hash_sha256         char(64)    NOT NULL,
    bytes               integer     NOT NULL CHECK (bytes > 0),
    ts                  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_evidencia_regtab ON evidencia(registro_tablero_id);
COMMENT ON TABLE  evidencia IS 'Fotografía de respaldo. Fecha, hora y autor los pone el sistema, nunca el operador (RF-05).';
COMMENT ON COLUMN evidencia.hash_sha256 IS 'Huella calculada al recibir el archivo. Es una denormalización deliberada: el valor probatorio depende de haberse calculado en el instante de la captura, de modo que recalcularlo después no probaría nada.';


CREATE TABLE evidencia_item (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidencia_id     bigint NOT NULL REFERENCES evidencia(id)      ON DELETE CASCADE,
    itemchecklist_id bigint NOT NULL REFERENCES item_checklist(id) ON DELETE RESTRICT,
    CONSTRAINT uq_evidencia_item UNIQUE (evidencia_id, itemchecklist_id)
);

COMMENT ON TABLE evidencia_item IS 'Relación N:M. Una misma fotografía respalda varios puntos de la pauta: la foto del tablero abierto evidencia tanto la revisión como el reapriete de lo que aparece en ella.';


CREATE TABLE observacion (
    id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_tablero_id bigint      NOT NULL REFERENCES registro_tablero(id) ON DELETE RESTRICT,
    registro_item_id    bigint      REFERENCES registro_item(id)             ON DELETE RESTRICT,
    autor_id            bigint      NOT NULL REFERENCES usuario(id)          ON DELETE RESTRICT,
    texto               text        NOT NULL,
    ts                  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_observacion_regtab ON observacion(registro_tablero_id);
COMMENT ON TABLE observacion IS 'Comentario anexado a un registro sin potestad para alterarlo. Es el canal por el que se aporta información sobre algo ya sellado, incluido el estudiante dual.';


CREATE TABLE hallazgo (
    id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_tablero_id bigint      NOT NULL REFERENCES registro_tablero(id) ON DELETE RESTRICT,
    usuario_id          bigint      NOT NULL REFERENCES usuario(id)          ON DELETE RESTRICT,
    criticidad          varchar(10) NOT NULL,
    descripcion         text        NOT NULL,
    ts                  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_hallazgo_criticidad CHECK (criticidad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA'))
);

CREATE INDEX ix_hallazgo_regtab ON hallazgo(registro_tablero_id);
COMMENT ON TABLE hallazgo IS 'Anomalía detectada durante la visita (RF-10). Alimenta la detección temprana.';


CREATE TABLE pendiente (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_id  bigint      NOT NULL REFERENCES visita(id)  ON DELETE RESTRICT,
    tablero_id bigint      NOT NULL REFERENCES tablero(id) ON DELETE RESTRICT,
    usuario_id bigint      NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    motivo     varchar(20) NOT NULL,
    comentario text        NOT NULL DEFAULT '',
    ts         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_pendiente_visita_tablero UNIQUE (visita_id, tablero_id),
    CONSTRAINT ck_pendiente_motivo CHECK (motivo IN
        ('SIN_ACCESO', 'EN_OPERACION', 'SIN_MATERIAL', 'TIEMPO', 'NO_EXISTE', 'OTRO')),
    CONSTRAINT ck_pendiente_otro CHECK (
        motivo <> 'OTRO' OR length(trim(comentario)) > 0
    )
);

CREATE INDEX ix_pendiente_visita ON pendiente(visita_id);
COMMENT ON TABLE pendiente IS 'Declaración explícita de un tablero no intervenido (RF-07). Es la única salida legítima para cerrar una visita con cobertura incompleta, y obliga a nombrar el motivo en lugar de dejar el silencio del papel.';


CREATE TABLE material_faltante (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_id   bigint       NOT NULL REFERENCES visita(id)  ON DELETE RESTRICT,
    -- El tablero es opcional a propósito: hay faltantes que bloquean un tablero
    -- concreto y faltantes de consumo general del local. Forzar la asociación
    -- obligaría a inventar un dato, y un dato inventado contamina la consulta
    -- que después pregunta qué comprar.
    tablero_id  bigint       REFERENCES tablero(id) ON DELETE RESTRICT,
    usuario_id  bigint       NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    descripcion varchar(200) NOT NULL,
    cantidad    smallint     NOT NULL DEFAULT 1,
    unidad      varchar(10)  NOT NULL DEFAULT 'UNIDAD',
    urgencia    varchar(10)  NOT NULL DEFAULT 'PROXIMO',
    comentario  text         NOT NULL DEFAULT '',
    ts          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_material_cantidad_positiva CHECK (cantidad >= 1),
    CONSTRAINT ck_material_descripcion_no_vacia CHECK (length(trim(descripcion)) > 0),
    CONSTRAINT ck_material_unidad CHECK (unidad IN
        ('UNIDAD', 'METRO', 'CAJA', 'JUEGO', 'KILO', 'LITRO')),
    CONSTRAINT ck_material_urgencia CHECK (urgencia IN
        ('BLOQUEA', 'PROXIMO', 'STOCK'))
);

CREATE INDEX ix_material_visita  ON material_faltante(visita_id);
CREATE INDEX ix_material_tablero ON material_faltante(tablero_id);
COMMENT ON TABLE material_faltante IS 'Material o repuesto que faltó en terreno (RF-11). Ataca la manifestación P6 del diagnóstico: hoy el faltante se avisa por mensajería y la compra se hace cuando alguien se acuerda, de modo que la cuadrilla vuelve al mismo local sin el repuesto y el tablero queda pendiente por segunda vez con el mismo motivo.';


CREATE TABLE medicion_electrica (
    id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_tablero_id bigint      NOT NULL UNIQUE REFERENCES registro_tablero(id) ON DELETE RESTRICT,
    usuario_id          bigint      NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    v_l1_l2 numeric(7,2), v_l2_l3 numeric(7,2), v_l3_l1 numeric(7,2),
    v_l1_n  numeric(7,2), v_l2_n  numeric(7,2), v_l3_n  numeric(7,2),
    v_l1_t  numeric(7,2), v_l2_t  numeric(7,2), v_l3_t  numeric(7,2),
    v_t_n   numeric(7,2),
    i_l1    numeric(8,2), i_l2    numeric(8,2), i_l3    numeric(8,2),
    cos_fi  numeric(4,3) CHECK (cos_fi IS NULL OR cos_fi BETWEEN 0 AND 1),
    observaciones text    NOT NULL DEFAULT '',
    ts      timestamptz   NOT NULL DEFAULT now()
);

COMMENT ON TABLE medicion_electrica IS 'Digitalización de la hoja «MEDICIONES ELECTRICAS» N° 002214 (RF-17). En papel trae tres columnas fijas; aquí se asocia al tablero concreto, de modo que un local con cinco tableros no se quede sin casilleros.';


