-- =============================================================================
--  SIG IMELSE — Esquema de la base de datos
--  ICN-292 Sistemas de Información para la Gestión · UTFSM · 2026-2
--
--  Motor: PostgreSQL 16
--  Uso:   psql -U imelse -d sig_imelse -f db/schema.sql
--
--  Modelo normalizado hasta 3FN. La justificación de la normalización y el
--  diccionario de datos completo están en docs/03-modelo-datos.md.
--
--  Dos decisiones de diseño que conviene leer antes del esquema:
--
--  1. TODA tabla de ejecución es append-only. Las respuestas del checklist,
--     las evidencias, las observaciones y los hallazgos no se actualizan ni se
--     eliminan: una corrección es una fila nueva encadenada a la original
--     mediante registro_item.corrige_a_id. Esa regla es el requisito RNF-02 y
--     es la razón de ser del sistema: un registro editable no prueba nada.
--
--  2. Las claves primarias son subrogadas, no naturales. El caso de tablero es
--     el más claro: su código es un dato de terreno que puede corregirse, y si
--     fuera la clave primaria, corregir un dígito obligaría a reescribir todo
--     el historial que lo referencia. La regla real del negocio se declara
--     aparte, como índice único sobre (local_id, codigo).
-- =============================================================================

